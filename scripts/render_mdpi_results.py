#!/usr/bin/env python3
"""Render deterministic MDPI tables before and after the V10 native campaign.

With no ``--analysis`` argument the renderer emits an explicit, compileable
pre-result placeholder.  With a named single-host analysis it fails closed
unless all 28 preregistered axes and the frozen measurement commit are present.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Mapping

ROOT = Path(__file__).resolve().parent.parent
PREMEASUREMENT = ROOT / "docs/paper/generated/premeasurement_tables.json"
DEFAULT_OUTPUT = ROOT / "paper/mdpi_working/generated"
FROZEN_MEASUREMENT_COMMIT = "1aeadb97e0409227aa203ba825a6bfc1d90445bc"
EXPECTED_AXIS_COUNT = 28
EXPECTED_COMPONENTS = {
    "committed-corpus-refresh": 8,
    "kyberslash-contrast": 10,
    "falcon-contrast": 6,
    "diverse-lineages": 4,
}
ALLOWED_STATES = {
    "risk-detected",
    "needs-review",
    "inconclusive",
    "no-finding-observed",
}


class RenderError(ValueError):
    """The paper input is incomplete or violates the frozen result contract."""


def _load_json(path: Path, label: str) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RenderError(f"{label} is unreadable: {exc}") from exc
    if not isinstance(data, dict):
        raise RenderError(f"{label} must be a JSON object")
    return data


def _tex(value: object) -> str:
    text = str(value)
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in text)


def _int(value: object, label: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise RenderError(f"{label} must be an integer")
    return value


def _finite_number(value: object, label: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise RenderError(f"{label} must be numeric")
    number = float(value)
    if not math.isfinite(number):
        raise RenderError(f"{label} must be finite")
    return number


def _render_static(data: Mapping[str, Any]) -> str:
    if data.get("kind") != "ctkat-premeasurement-paper-artifacts":
        raise RenderError("premeasurement input kind mismatch")
    counts = data.get("corpus_state_counts")
    campaign = data.get("measurement_campaign")
    ablation = data.get("ablation")
    if not isinstance(counts, Mapping) or set(counts) != ALLOWED_STATES:
        raise RenderError("premeasurement corpus states are incomplete")
    if not isinstance(campaign, Mapping) or campaign.get("timing_axes") != EXPECTED_AXIS_COUNT:
        raise RenderError("premeasurement campaign is not the 28-axis V10 plan")
    components = campaign.get("components")
    if not isinstance(components, list) or len(components) != 4:
        raise RenderError("premeasurement campaign must contain four components")
    if not isinstance(ablation, Mapping) or not isinstance(ablation.get("stages"), list):
        raise RenderError("premeasurement ablation is missing")

    lines = [
        "% Generated by scripts/render_mdpi_results.py; do not edit.",
        r"\begin{table}[H]",
        r"\caption{Fail-closed states in the committed screening corpus. Counts refer to target--harness pairs and must not be interpreted as an accuracy rate.\label{tab:corpus-states}}",
        r"\begin{tabularx}{\textwidth}{Lr}",
        r"\toprule",
        r"\textbf{Evidence state} & \textbf{Pairs}\\",
        r"\midrule",
    ]
    for state in ("risk-detected", "needs-review", "inconclusive", "no-finding-observed"):
        lines.append(rf"\texttt{{{_tex(state)}}} & {_int(counts[state], state)}\\")
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabularx}",
            r"\end{table}",
            "",
            r"\begin{table}[H]",
            r"\caption{Candidate-generation ablation. The first three rows measure review burden, not detection accuracy; only the reviewed fold emits final evidence states.\label{tab:ablation}}",
            r"\begin{tabularx}{\textwidth}{Lrrrr}",
            r"\toprule",
            r"\textbf{Stage} & \textbf{Cells} & \textbf{CT findings} & \textbf{Asm candidates} & \textbf{Candidate pairs}\\",
            r"\midrule",
        ]
    )
    stage_labels = {
        "single-release-build": "Single release build",
        "full-build-matrix": "Full compiler/flag matrix",
        "full-matrix-plus-asm": "Matrix plus assembly scan",
        "reviewed-evidence-fold": "Reviewed fail-closed fold",
    }
    stages = {item.get("stage"): item for item in ablation["stages"] if isinstance(item, Mapping)}
    for stage_id, label in stage_labels.items():
        row = stages.get(stage_id)
        if row is None:
            raise RenderError(f"ablation stage missing: {stage_id}")
        values = []
        for field in ("cells", "ct_finding_pairs", "asm_candidate_pairs", "candidate_pairs"):
            value = row.get(field)
            values.append("--" if value == "" else str(_int(value, f"{stage_id}.{field}")))
        lines.append(rf"{_tex(label)} & {' & '.join(values)}\\")
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabularx}",
            r"\end{table}",
            "",
            r"\begin{table}[H]",
            r"\caption{Frozen V10 native timing scope. Target executions are component-local and are not counts of independent implementations.\label{tab:v10-scope}}",
            r"\begin{tabularx}{\textwidth}{Lrrr}",
            r"\toprule",
            r"\textbf{Component} & \textbf{Targets} & \textbf{Axes} & \textbf{Protocol rows}\\",
            r"\midrule",
        ]
    )
    seen: dict[str, int] = {}
    for item in components:
        if not isinstance(item, Mapping):
            raise RenderError("campaign component must be an object")
        component_id = str(item.get("id"))
        axes = _int(item.get("timing_axes"), f"{component_id}.timing_axes")
        seen[component_id] = axes
        lines.append(
            rf"\texttt{{{_tex(component_id)}}} & "
            rf"{_int(item.get('targets'), f'{component_id}.targets')} & {axes} & "
            rf"{_int(item.get('protocol_rows'), f'{component_id}.protocol_rows'):,}\\"
        )
    if seen != EXPECTED_COMPONENTS:
        raise RenderError(f"campaign component/axis drift: {seen}")
    lines.extend(
        [
            r"\midrule",
            rf"Total & {_int(campaign.get('target_executions'), 'target_executions')} & "
            rf"{_int(campaign.get('timing_axes'), 'timing_axes')} & "
            rf"{_int(campaign.get('protocol_rows_per_host'), 'protocol_rows_per_host'):,}\\",
            r"\bottomrule",
            r"\end{tabularx}",
            r"\end{table}",
            "",
        ]
    )
    return "\n".join(lines)


def _validate_analysis(data: Mapping[str, Any], expected_commit: str) -> None:
    if data.get("schema_version") != "1.0":
        raise RenderError("native analysis schema version mismatch")
    if data.get("kind") != "paper-native-single-host-analysis":
        raise RenderError("MDPI result renderer accepts only named single-host analysis")
    if (
        data.get("measurement_commit") != expected_commit
        or data.get("ctkat_commit") != expected_commit
        or data.get("verification_commit") != expected_commit
    ):
        raise RenderError("native analysis is not bound to the frozen measurement commit")
    if re.fullmatch(r"[0-9a-f]{40}", expected_commit) is None:
        raise RenderError("expected measurement commit must be a full SHA-1")
    if not isinstance(data.get("bundle_id"), str) or not data["bundle_id"]:
        raise RenderError("native analysis bundle_id is missing")
    if re.fullmatch(r"[0-9a-f]{64}", str(data.get("input_aggregate_sha256"))) is None:
        raise RenderError("native analysis input aggregate hash is invalid")
    summary = data.get("summary")
    axes = data.get("primary_axes")
    hosts = data.get("hosts")
    if not isinstance(summary, Mapping) or not isinstance(axes, list):
        raise RenderError("native analysis summary or axes missing")
    if _int(summary.get("axis_count"), "summary.axis_count") != EXPECTED_AXIS_COUNT:
        raise RenderError("native analysis summary does not declare 28 axes")
    if len(axes) != EXPECTED_AXIS_COUNT:
        raise RenderError("native analysis must contain exactly 28 primary axes")
    if not isinstance(hosts, list) or len(hosts) != 1 or not isinstance(hosts[0], Mapping):
        raise RenderError("native analysis must contain exactly one physical host")
    declared_host = hosts[0]
    if not isinstance(declared_host.get("id"), str) or not declared_host["id"]:
        raise RenderError("native analysis host id is missing")
    if not isinstance(declared_host.get("cpu_model"), str) or not declared_host["cpu_model"]:
        raise RenderError("native analysis CPU model is missing")
    if re.fullmatch(r"[0-9a-f]{64}", str(declared_host.get("machine_id_sha256"))) is None:
        raise RenderError("native analysis machine identity hash is invalid")
    counts = summary.get("combined_status_counts")
    if not isinstance(counts, Mapping) or set(counts) != ALLOWED_STATES:
        raise RenderError("native analysis state counts are incomplete")
    if (
        sum(_int(counts[state], f"summary.{state}") for state in ALLOWED_STATES)
        != EXPECTED_AXIS_COUNT
    ):
        raise RenderError("native analysis state counts do not sum to 28")

    keys: set[tuple[str, str, str, str]] = set()
    components: dict[str, int] = defaultdict(int)
    observed_states: dict[str, int] = {state: 0 for state in ALLOWED_STATES}
    for index, axis in enumerate(axes):
        if not isinstance(axis, Mapping):
            raise RenderError(f"primary_axes[{index}] must be an object")
        key = tuple(
            str(axis.get(name) or "") for name in ("component", "target", "harness", "axis")
        )
        if any(not value for value in key) or key in keys:
            raise RenderError(f"primary_axes[{index}] has a missing or duplicate identity")
        if any(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._/+:-]*", value) is None for value in key):
            raise RenderError(f"primary_axes[{index}] identity is unsafe for deterministic LaTeX")
        keys.add(key)
        components[key[0]] += 1
        state = axis.get("combined_status")
        if state not in ALLOWED_STATES:
            raise RenderError(f"primary_axes[{index}] has an invalid evidence state")
        observed_states[str(state)] += 1
        results = axis.get("host_results")
        if (
            not isinstance(results, list)
            or len(results) != 1
            or not isinstance(results[0], Mapping)
        ):
            raise RenderError(f"primary_axes[{index}] must contain one host result")
        host = results[0]
        if host.get("host_id") != declared_host.get("id"):
            raise RenderError(f"primary_axes[{index}] host identity drift")
        if host.get("cpu_model") != declared_host.get("cpu_model") or host.get(
            "machine_id_sha256"
        ) != declared_host.get("machine_id_sha256"):
            raise RenderError(f"primary_axes[{index}] host metadata drift")
        if host.get("raw_status") not in {"PASS", "WARNING", "FAIL"}:
            raise RenderError(f"primary_axes[{index}] raw status invalid")
        if host.get("timing_validity") not in {
            "valid",
            "confounded",
            "insufficient-power",
            "invalid",
        }:
            raise RenderError(f"primary_axes[{index}] timing validity invalid")
        raw_status = str(host["raw_status"])
        validity = str(host["timing_validity"])
        expected_signal = {
            "PASS": "no-signal-observed",
            "WARNING": "warning",
            "FAIL": "signal",
        }[raw_status]
        if host.get("timing_signal") != expected_signal:
            raise RenderError(f"primary_axes[{index}] timing signal/raw status drift")
        expected_state = (
            "inconclusive"
            if validity != "valid"
            else {
                "PASS": "no-finding-observed",
                "WARNING": "needs-review",
                "FAIL": "risk-detected",
            }[raw_status]
        )
        if state != expected_state:
            raise RenderError(f"primary_axes[{index}] evidence state/raw validity drift")
        t_score = _finite_number(host.get("t_score"), f"primary_axes[{index}].t_score")
        abs_t_score = _finite_number(host.get("abs_t_score"), f"primary_axes[{index}].abs_t_score")
        if not math.isclose(abs(t_score), abs_t_score, rel_tol=1e-12, abs_tol=1e-12):
            raise RenderError(f"primary_axes[{index}] signed/absolute t-score drift")
        if _int(host.get("n0"), f"primary_axes[{index}].n0") <= 0:
            raise RenderError(f"primary_axes[{index}].n0 must be positive")
        if _int(host.get("n1"), f"primary_axes[{index}].n1") <= 0:
            raise RenderError(f"primary_axes[{index}].n1 must be positive")
        repeats = host.get("repeat_class_mean_deltas")
        if not isinstance(repeats, list) or len(repeats) != 3:
            raise RenderError(f"primary_axes[{index}] must contain three process repeats")
        for repeat_index, value in enumerate(repeats):
            _finite_number(value, f"primary_axes[{index}].repeat[{repeat_index}]")
        heterogeneity = axis.get("host_heterogeneity")
        if (
            not isinstance(heterogeneity, Mapping)
            or heterogeneity.get("applicability") != "not-applicable-single-host"
            or heterogeneity.get("warning") is not False
        ):
            raise RenderError(f"primary_axes[{index}] fabricates single-host heterogeneity")
    if dict(components) != EXPECTED_COMPONENTS:
        raise RenderError(f"native analysis component/axis drift: {dict(components)}")
    declared_states = {state: _int(counts[state], f"summary.{state}") for state in ALLOWED_STATES}
    if observed_states != declared_states:
        raise RenderError(
            f"native analysis summary/axis state drift: {declared_states} != {observed_states}"
        )


def _render_native_summary_pending() -> str:
    return "\n".join(
        [
            "% Generated by scripts/render_mdpi_results.py; do not edit.",
            r"\NativeResultsAvailablefalse",
            r"\renewcommand{\NativeAbstractSentence}{The preregistered native timing campaign is intentionally not summarized in this pre-result draft because its complete, hash-validated named analysis is not yet available.}",
            r"\renewcommand{\NativeResultSummary}{The preregistered V10 single-host campaign is still being acquired or validated. No partial, pilot, engineering, or legacy timing value is reported in this draft.}",
            "",
        ]
    )


def _render_native_pending() -> str:
    return "\n".join(
        [
            "% Generated by scripts/render_mdpi_results.py; do not edit.",
            r"\begin{table}[H]",
            r"\caption{Reserved location for the 28-axis V10 native timing analysis. This table will be generated only from a complete, hash-validated schema-v5 bundle.\label{tab:native-results}}",
            r"\begin{tabularx}{\textwidth}{L}",
            r"\toprule",
            r"\textbf{Pre-result state}\\",
            r"\midrule",
            r"\texttt{NATIVE-RESULTS-PENDING}: final values intentionally withheld until deterministic named analysis passes all validators.\\",
            r"\bottomrule",
            r"\end{tabularx}",
            r"\end{table}",
            "",
        ]
    )


def _render_native_summary(data: Mapping[str, Any], expected_commit: str) -> str:
    _validate_analysis(data, expected_commit)
    summary = data["summary"]
    counts = summary["combined_status_counts"]
    host = data["hosts"][0]
    return "\n".join(
        [
            "% Generated by scripts/render_mdpi_results.py; do not edit.",
            r"\NativeResultsAvailabletrue",
            rf"\renewcommand{{\NativeMeasurementCommit}}{{\texttt{{\seqsplit{{{_tex(expected_commit)}}}}}}}",
            rf"\renewcommand{{\NativeHostModel}}{{{_tex(host.get('cpu_model', 'unavailable'))}}}",
            "\\renewcommand{\\NativeAbstractSentence}{The validated single-host campaign "
            f"classified {counts['risk-detected']} axes as risk-detected, "
            f"{counts['needs-review']} as needs-review, {counts['inconclusive']} as inconclusive, "
            f"and {counts['no-finding-observed']} as no-finding-observed under the frozen host "
            "and protocol.}",
            "\\renewcommand{\\NativeResultSummary}{On host \\NativeHostModel{}, the validated "
            f"single-host analysis contains {EXPECTED_AXIS_COUNT} axes: "
            f"{counts['risk-detected']} risk-detected, {counts['needs-review']} needs-review, "
            f"{counts['inconclusive']} inconclusive, and "
            f"{counts['no-finding-observed']} no-finding-observed. The analysis is bound to "
            "commit \\NativeMeasurementCommit{}.}",
            "",
        ]
    )


def _render_native(data: Mapping[str, Any], expected_commit: str) -> str:
    _validate_analysis(data, expected_commit)
    grouped: dict[str, list[Mapping[str, Any]]] = defaultdict(list)
    for axis in data["primary_axes"]:
        grouped[str(axis["component"])].append(axis)

    lines = [
        "% Generated by scripts/render_mdpi_results.py; do not edit.",
    ]
    for table_index, component in enumerate(EXPECTED_COMPONENTS, start=1):
        axes = sorted(
            grouped[component],
            key=lambda item: (str(item["target"]), str(item["harness"]), str(item["axis"])),
        )
        lines.extend(
            [
                # Keep component tables in protocol order and before the
                # interpretation paragraph that follows the generated block.
                r"\begin{table}[H]",
                rf"\caption{{Validated V10 timing results for \texttt{{{_tex(component)}}}. Each row is scoped to the recorded physical host and protocol.\label{{tab:native-results-{table_index}}}}}",
                r"\begin{adjustwidth}{-\extralength}{0cm}",
                r"\begingroup",
                r"\scriptsize",
                r"\setlength{\tabcolsep}{3pt}",
                r"\begin{tabularx}{\fulllength}{LLcrrLL}",
                r"\toprule",
                r"\textbf{Target} & \textbf{Harness/axis} & \textbf{Raw} & \textbf{$|t|$} & \textbf{$n_0/n_1$} & \textbf{Validity} & \textbf{State}\\",
                r"\midrule",
            ]
        )
        for axis in axes:
            result = axis["host_results"][0]
            lines.append(
                rf"\path{{{axis['target']}}} & "
                rf"\path{{{axis['harness']}/{axis['axis']}}} & "
                rf"\texttt{{{_tex(result['raw_status'])}}} & "
                rf"{_finite_number(result['abs_t_score'], 'abs_t_score'):.4g} & "
                rf"{_int(result['n0'], 'n0')}/{_int(result['n1'], 'n1')} & "
                rf"\path{{{result['timing_validity']}}} & "
                rf"\path{{{axis['combined_status']}}}\\"
            )
        lines.extend(
            [
                r"\bottomrule",
                r"\end{tabularx}",
                r"\endgroup",
                r"\end{adjustwidth}",
                r"\end{table}",
                "",
            ]
        )
    return "\n".join(lines)


def build_outputs(
    *,
    premeasurement_path: Path = PREMEASUREMENT,
    analysis_path: Path | None = None,
    output_root: Path = DEFAULT_OUTPUT,
    expected_commit: str = FROZEN_MEASUREMENT_COMMIT,
) -> dict[Path, str]:
    premeasurement = _load_json(premeasurement_path, "premeasurement paper artifacts")
    static = _render_static(premeasurement)
    if analysis_path is None:
        native_summary = _render_native_summary_pending()
        native = _render_native_pending()
        state = {
            "schema_version": 1,
            "kind": "ctkat-mdpi-render-state",
            "native_results": "pending",
            "measurement_commit": expected_commit,
            "expected_axes": EXPECTED_AXIS_COUNT,
            "analysis_input": None,
        }
    else:
        analysis = _load_json(analysis_path, "named native analysis")
        native_summary = _render_native_summary(analysis, expected_commit)
        native = _render_native(analysis, expected_commit)
        state = {
            "schema_version": 1,
            "kind": "ctkat-mdpi-render-state",
            "native_results": "complete",
            "measurement_commit": expected_commit,
            "expected_axes": EXPECTED_AXIS_COUNT,
            # The hash binds the bytes.  Keeping only the basename avoids embedding
            # a workstation-specific absolute path in a deterministic paper input.
            "analysis_input": analysis_path.name,
            "analysis_input_sha256": hashlib.sha256(analysis_path.read_bytes()).hexdigest(),
            "input_aggregate_sha256": analysis["input_aggregate_sha256"],
            "bundle_id": analysis["bundle_id"],
        }
    return {
        output_root / "static_results.tex": static,
        output_root / "native_summary.tex": native_summary,
        output_root / "native_results.tex": native,
        output_root / "render_state.json": json.dumps(state, indent=2, sort_keys=True) + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--premeasurement", type=Path, default=PREMEASUREMENT)
    parser.add_argument("--analysis", type=Path)
    parser.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--expected-commit", default=FROZEN_MEASUREMENT_COMMIT)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        outputs = build_outputs(
            premeasurement_path=args.premeasurement,
            analysis_path=args.analysis,
            output_root=args.output_root,
            expected_commit=args.expected_commit,
        )
    except (OSError, RenderError) as exc:
        print(f"[mdpi-results] ERROR: {exc}", file=sys.stderr)
        return 2
    if args.write:
        args.output_root.mkdir(parents=True, exist_ok=True)
        for path, content in outputs.items():
            path.write_text(content, encoding="utf-8")
        print(f"[mdpi-results] wrote {len(outputs)} deterministic files")
        return 0
    stale = [
        path
        for path, content in outputs.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]
    if stale:
        for path in stale:
            try:
                label = path.relative_to(ROOT)
            except ValueError:
                label = path
            print(f"[mdpi-results] ERROR: stale or missing: {label}", file=sys.stderr)
        return 1
    print("[mdpi-results] OK: deterministic MDPI tables are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
